-- Пункт 05: повтор мобильной отправки после потери ответа не должен
-- создавать вторую запись. Каждое сообщение несёт стабильный ключ
-- идемпотентности, сгенерированный клиентом один раз на черновик.
ALTER TABLE messages ADD COLUMN client_msg_id UUID;

-- Полный (не частичный) уникальный индекс: NULL между собой не конфликтуют,
-- поэтому старые строки без ключа не затрагиваются, а PostgREST-повтор
-- через onConflict=client_msg_id находит арбитр конфликта.
CREATE UNIQUE INDEX messages_client_msg_id_uidx ON messages(client_msg_id);
